function folder = exportRun(in, root)
%EXPORTRUN Write one finished run as a versioned, checksummed package (mg-v2-runpkg/1.0). SIMULATION ONLY.
%   folder = mgv2.run.exportRun(in, root)     in: from mgv2.ui.MissionSession.packageInputs
%   The package is assembled in a hidden ".partial-" folder beside its final name and renamed only after every file
%   is written and hashed, so a failure never leaves a package that looks complete. An existing package is never
%   overwritten. Any failure raises mgv2:ExportFailed (or mgv2:TruthLeak) and removes the partial folder.
%
%   Layout under folder = <run_id>_g<generation>_<yyyymmddTHHMMSSZ>:
%     manifest.json            schema, run, end state, counts, provenance, limitations
%     config/run_config.mat    mission, sensor and environment configuration exactly as run (authoritative)
%     config/run_config.json   the same, for reading
%     telemetry/poses.mat      every PoseSample row (MissionEngine.poseLog), authoritative
%     telemetry/poses.csv      the same, for reading
%     telemetry/phases.csv     phase transitions
%     samples/<SENSOR>.mat     every public sample of that sensor, in emission order (cell row "samples")
%     samples/index.csv        one row per sample: SensorSystem.Log plus sample_sha256 (mgv2.run.digest)
%     events/events.json       SUSPECTED events and source information at export time
%     events/events.mat        the same events, exactly as listed (used to check a replay)
%     events/evidence.mat      verified evidence record of every listed event, or the reason it could not be read
%     files.sha256             SHA-256 of every other file, sorted by path
%   Not exported: private scene radiometry, surface features or any truth. The world is regenerated by
%   mgv2.scene.buildWorld and identified by world_digest.
schema = "mg-v2-runpkg/1.0"; id = 'mgv2:ExportFailed';
root = string(root);
if ~isfolder(root), [ok, msg] = mkdir(root); if ~ok, error(id, 'Cannot create export folder %s: %s', root, msg); end, end
mgv2.sensors.assertPublic(rmfield(in, 'samples'), "export");
if in.end_state.state ~= "ENDED", error(id, 'Only a finished run can be exported (state %s).', in.end_state.state); end

name = sprintf('%s_g%d_%s', regexprep(char(in.mission.run_id), '[^A-Za-z0-9_-]', '_'), in.generation, ...
    char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyyMMdd''T''HHmmss''Z''')));
folder = fullfile(root, name); tmp = fullfile(root, ".partial-" + name);
if isfolder(folder) || isfile(folder), error(id, 'Package %s already exists; it is never overwritten.', folder); end
if isfolder(tmp), rmdir(tmp, 's'); end
try
    for d = ["config", "telemetry", "samples", "events"], mkdir(fullfile(tmp, d)); end
    % samples: every log row must have exactly one recorded sample, in the same order
    L = in.sensor_log; L.sample_sha256 = strings(height(L), 1); counts = struct();
    for sid = mgv2.sensors.SensorSystem.Order
        samples = in.samples.(sid); rows = find(L.sensor_id == sid);
        if numel(samples) ~= numel(rows), error(id, '%s: %d samples recorded but %d logged.', sid, numel(samples), numel(rows)); end
        for k = 1:numel(rows)
            s = samples{k};
            if string(s.frame_id) ~= L.frame_id(rows(k)), error(id, '%s: recorded sample %d is not the logged frame.', sid, k); end
            L.sample_sha256(rows(k)) = mgv2.run.digest(s);
        end
        save(fullfile(tmp, "samples", sid + ".mat"), 'samples', '-v7');
        counts.(sid) = numel(samples);
    end
    writetable(L, fullfile(tmp, "samples", "index.csv"));
    cfg = struct('mission', in.mission, 'sensors', in.sensors, 'environment', in.environment, 'scenario', in.scenario);
    v21 = isfield(in, 'scene_config') && (~isequaln(in.scene_config, mgv2.scene.defaultSceneConfig()) || in.private_forward_model.used);
    if v21, cfg.scene_config = in.scene_config; schema = "mg-v2-runpkg/1.1"; end   % 1.0 stays byte-for-byte V2
    save(fullfile(tmp, "config", "run_config.mat"), '-struct', 'cfg');
    writeText(fullfile(tmp, "config", "run_config.json"), jsonencode(cfg, 'PrettyPrint', true));
    poses = in.poses;
    save(fullfile(tmp, "telemetry", "poses.mat"), 'poses');
    writetable(in.poses, fullfile(tmp, "telemetry", "poses.csv"));
    writetable(in.phases, fullfile(tmp, "telemetry", "phases.csv"));
    ev = struct('events', in.events, 'source', in.source, 'notice', "SUSPECTED anomalies from a simulation, uncalibrated scores");
    writeText(fullfile(tmp, "events", "events.json"), jsonencode(ev, 'PrettyPrint', true));
    events = in.events;
    save(fullfile(tmp, "events", "events.mat"), 'events');
    evidence = in.evidence;
    save(fullfile(tmp, "events", "evidence.mat"), 'evidence', '-v7');

    m = struct('schema_version', schema, 'package', string(name), 'simulation_only', true, ...
        'notice', "SIMULATION ONLY. Every event is a SUSPECTED anomaly with an uncalibrated score. No real sensor, flight or detection.", ...
        'run_id', string(in.mission.run_id), 'generation', in.generation, 'scenario', in.scenario, 'seed', in.mission.seed, ...
        'synthetic_targets_in_scene', 0, ...
        'target_note', "The live scenarios place no synthetic target, so every SUSPECTED event in this run is on target-free ground.", ...
        'end_state', in.end_state, 'counts', struct('poses', height(in.poses), 'samples', counts, 'events', numel(in.events)), ...
        'world_digest', in.world_digest, 'provenance', in.provenance, ...
        'created_utc', string(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z''')), ...
        'integrity', "files.sha256 lists the SHA-256 of every other file. It detects changed, missing or extra files; it is not a signature.");
    if v21, m.private_forward_model = in.private_forward_model; end   % 1.1 only: SHA-256 commitment, never positions
    mgv2.sensors.assertPublic(m, "manifest");
    writeText(fullfile(tmp, "manifest.json"), jsonencode(m, 'PrettyPrint', true));

    files = mgv2.run.listFiles(tmp); lines = strings(numel(files), 1);
    for k = 1:numel(files), lines(k) = mgv2.run.fileSha256(fullfile(tmp, files(k))) + "  " + files(k); end
    writeText(fullfile(tmp, "files.sha256"), strjoin(lines, newline) + newline);
    [ok, msg] = movefile(tmp, folder);
    if ~ok, error(id, 'Could not finalise the package: %s', msg); end
catch err
    if isfolder(tmp), rmdir(tmp, 's'); end
    if any(strcmp(err.identifier, {id, 'mgv2:TruthLeak'})), rethrow(err); end
    error(id, 'Export failed: %s', err.message);
end
folder = string(folder);
end

function writeText(f, txt)
fid = fopen(f, 'w', 'n', 'UTF-8');
if fid < 0, error('mgv2:ExportFailed', 'Cannot write %s.', f); end
c = onCleanup(@() fclose(fid)); fwrite(fid, unicode2native(char(txt), 'UTF-8'));
end
