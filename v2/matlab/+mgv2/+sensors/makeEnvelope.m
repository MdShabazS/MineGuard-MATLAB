function s = makeEnvelope(mission, sensorCfg, pose, seq, valid, reason, coordFrame, footprint, quality)
%MAKEENVELOPE Common mg-v2-sensors/1.0 envelope (V2-004 §2.2), exact field set and order.
%   s = mgv2.sensors.makeEnvelope(mission, sensorCfg, pose, seq, valid, reason, coordFrame, footprint, quality)
%   mission: struct(run_id, scenario_id); pose: V2-002 PoseSample (pose_id, tick_id, t_s are COPIED from
%   it, never minted). data_ref "NOT_PERSISTED" = explicit absent value until a run package is written.
c = mgv2.sensors.contract();
if ~ismember(reason, c.invalid_reasons), error('mgv2:InvalidSample', 'Unknown invalid_reason "%s".', reason); end
if valid ~= (reason == "NONE"), error('mgv2:InvalidSample', 'valid must be true iff invalid_reason is NONE.'); end
if isempty(footprint), footprint = zeros(0, 2); end
s = struct('schema_version', c.schema_version, 'run_id', string(mission.run_id), 'scenario_id', string(mission.scenario_id), ...
    'sensor_id', sensorCfg.sensor_id, 'sample_seq', uint64(seq), 'pose_id', uint64(pose.pose_id), 'tick_id', uint64(pose.tick_id), ...
    't_s', pose.t_s, 'simulated', true, 'valid', logical(valid), 'invalid_reason', string(reason), ...
    'sensor_model_version', sensorCfg.model_version, ...
    'frame_id', sprintf("%s/%s/%06d", mission.run_id, sensorCfg.sensor_id, seq), ...
    'coordinate_frame', string(coordFrame), 'footprint_enu_m', footprint, 'data_ref', "NOT_PERSISTED", ...
    'calibration_kind', "SYNTHETIC_ASSUMED", 'quality', quality, 'units', sensorCfg.units);
end
