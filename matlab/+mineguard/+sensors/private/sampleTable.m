function S = sampleTable(ctx, kind, prefix)
%SAMPLETABLE Typed SensorSample table (mg-contract/1.0, exactly 11 columns), one row per pose.
%   Rows start invalid with NaN values; each model fills in the valid rows.
n = ctx.n;
S = table( ...
    compose(prefix + "-%06d", (1:n)'), ctx.ids, ctx.t, repmat(string(kind), n, 1), ...
    NaN(n,1), NaN(n,1), NaN(n,1), NaN(n,1), NaN(n,1), false(n,1), strings(n,1), ...
    'VariableNames', {'sample_id','pose_sample_id','t_s','sensor_kind','temperature_K', ...
    'response_norm','noise_sigma','standoff_m','footprint_radius_m','valid','invalid_reason'});
end
