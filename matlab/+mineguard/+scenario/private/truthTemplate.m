function truth = truthTemplate(n)
%TRUTHTEMPLATE Typed TargetTruth table with n rows (n may be 0).
%   Columns follow mg-contract/1.0 Section 2. A zero-row table keeps every
%   column and type rather than returning an untyped 0x0 double.
truth = table( ...
    strings(n,1), zeros(n,1), zeros(n,1), zeros(n,1), strings(n,1), ...
    categorical(repmat("target",n,1), ["target" "clutter"]), strings(n,1), false(n,1), ...
    'VariableNames', {'target_id','x_east_m','y_north_m','burial_depth_m', ...
                      'material_type','label','soil_class','surface_exposed'});
end
