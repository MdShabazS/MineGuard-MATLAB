function E = eventTable(n)
%EVENTTABLE Typed DetectionEvent table with exactly the 12 mg-contract/1.0 columns (n may be 0).
E = table(strings(n,1), zeros(n,1), zeros(n,1), zeros(n,1), NaN(n,1), NaN(n,1), ...
    strings(n,1), strings(n,1), strings(n,1), zeros(n,1), repmat("SUSPECTED", n, 1), true(n,1), ...
    'VariableNames', {'event_id','t_s','x_est_m','y_est_m','confidence_0_1','uncertainty_m', ...
    'thermal_sample_id','em_sample_id','method_name','threshold','status','valid'});
end
