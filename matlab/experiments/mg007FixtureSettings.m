%   or taken from, a real camera, coil, soil or object (docs/MG006 Sections 4-5).
%   293.15 K is a numerical baseline, not an observed soil temperature.
th = struct( ...
    'model_version', "mg007-thermal-proxy-0.1", ...
    'background_temperature_K', 293.15, ...
    'contrast_amplitude_K', 2.0, ...          % signed; 0 = negative control
    'thermal_depth_scale_m', 0.10, ...
    'camera_half_fov_rad', 0.35, ...          % about 20 deg half angle, hypothetical nadir camera
    'thermal_noise_sigma_K', 0.10, ...
    'thermal_object_radius_m', 0.15, ...
    'time_of_day_s', 43200, ...               % 12:00 scene reference
    'diurnal_mode', "static", ...
    'material_contrast_lookup', struct( ...
        'synthetic_cased_surrogate', 1.0, ...
        'synthetic_metal_cased_surrogate', 1.0, ...
        'synthetic_plastic_surrogate', 1.0, ...
        'synthetic_metal_debris', 0.5, ...
        'synthetic_rock', 3.0, ...            % a "hot harmless rock" can exceed a target
        'synthetic_root', -0.3));
em = struct( ...
    'model_version', "mg007-em-proxy-0.1", ...
    'em_model_kind', "phenomenological_em_proxy", ...
    'em_distance_scale_m', 0.30, ...
    'em_falloff_exponent', 3.0, ...           % shape assumption, not a field law
    'em_noise_sigma_norm', 0.02, ...
