    'coil_geometry_note', "Hypothetical concentric coil; no real device parameters implied.", ...
    'material_response_lookup', struct( ...
        'synthetic_cased_surrogate', 0.2, ... % assumed low metal content; NOT proof of metal
        'synthetic_metal_cased_surrogate', 1.0, ...
