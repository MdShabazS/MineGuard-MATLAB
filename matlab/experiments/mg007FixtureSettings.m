        'synthetic_metal_debris', 0.8, ...        % conductive clutter, not a target label
        'synthetic_rock', 0.0, ...
        'synthetic_root', 0.0));
ss = struct('version', "mg007-sensor-settings-0.1", 'thermal', th, 'em', em);
end
